/**
 * Writes src/dom/script.ts: the hanging pass as one minified expression, ready to be sent
 * inline. It is a fixed string rather than `hangPunctuation.toString()` at run time because
 * a server build and a client build print the same function differently (comments,
 * whitespace), and React would then see two different scripts on hydration.
 * Run it after changing src/dom/hang.ts: `bun run gen:script`. src/dom/script.test.ts fails
 * when the file is out of date.
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { hangPunctuation } from '../src/dom/hang';

export async function buildHangScript(): Promise<string> {
  const dir = mkdtempSync(join(tmpdir(), 'hang-'));
  const entry = join(dir, 'entry.js');
  // `hangPunctuation` is self-contained, so its source stands on its own.
  writeFileSync(
    entry,
    `globalThis.__hang = (${hangPunctuation.toString()})(document.currentScript.parentElement);`,
  );
  try {
    const result = await Bun.build({
      entrypoints: [entry],
      minify: true,
      target: 'browser',
      format: 'iife',
    });
    if (!result.success) throw new Error(result.logs.map(String).join('\n'));
    const code = (await result.outputs[0]?.text()) ?? '';
    // The bundle is `(function(s){...})(document.currentScript.parentElement)` minified to
    // `function(s){...}(document...)` once the wrapper and the assignment are stripped.
    const body = code
      .trim()
      .replace(/^\(\(\)=>\{/, '')
      .replace(/\}\)\(\);?$/, '')
      .replace('globalThis.__hang=', '');
    const match = /^(function[\s\S]*\})\(document\.currentScript\.parentElement\);?$/.exec(body);
    if (!match) throw new Error(`Unexpected shape of the minified script: ${body.slice(0, 80)}...`);
    return `(${match[1]})(document.currentScript.parentElement)`;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const code = await buildHangScript();
  const file = `/** Generated by scripts/gen-hang-script.ts from src/dom/hang.ts; do not edit. */\nexport const HANG_SCRIPT = ${JSON.stringify(code)};\n`;
  writeFileSync(new URL('../src/dom/script.ts', import.meta.url), file);
  console.log(`src/dom/script.ts: ${code.length} bytes`);
}
