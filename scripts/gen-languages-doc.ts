/**
 * Writes docs/languages/<code>.md (the code in lower case) for every language pack and docs/languages/index.md.
 * Everything on a page is read from the pack (src/core/lang/<code>.ts), so a page cannot
 * disagree with the engine.
 *
 *     bun scripts/gen-languages-doc.ts        (or: bun run docs:languages)
 *
 * Imports only from ../src and node:, so the package stays liftable.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type LangPack, type Level, NBSP, PACKS } from '../src/core';

const DIR = join(import.meta.dir, '..', 'docs', 'languages');

/** The file name of a pack, its page and its tests: the code in lower case (`de-CH` is `de-ch`). */
export const fileOf = (code: string): string => code.toLowerCase();

/** A no-break space is shown as `~`, as in docs/rules.md. */
const show = (text: string): string => text.replaceAll(NBSP, '~');
const code = (text: string): string => `\`${show(text)}\``;
const levelOf = ([open, close]: Level): string => code(`${open}…${close}`);
const levels = (list: readonly Level[]): string => list.map(levelOf).join(', ');

/** Typographic quotation marks; straight ones are left out, as they also quote the prose around. */
const MARK = '„‚«»‹›“”‘’';
/** A pattern of marks around an ellipsis, `„…“` or `«…“…‘…’…”…»`, as one word. */
const PATTERN = new RegExp(`(?<![\\p{L}\\d])[${MARK}…]*…[${MARK}…]*(?![\\p{L}\\d])`, 'gu');
/**
 * Prose that names quotation marks (a pack's notes and sources) puts each pattern of them in a code
 * span, so a page typesetting its text (the website's, in English) cannot turn them into its own.
 */
const marks = (text: string): string =>
  text
    .split(/(`[^`]*`)/)
    .map((part, i) =>
      i % 2
        ? part
        : part.replace(PATTERN, (found) =>
            [...found].some((ch) => MARK.includes(ch)) ? `\`${found}\`` : found,
          ),
    )
    .join('');

function dialogueSetting(pack: LangPack): string {
  const style = pack.dialogueDash;
  if (!style) return 'not set (dialogue is quoted)';
  const dash = style.mark === '—' ? 'em dash' : 'en dash';
  return `${dash} ${style.attached ? 'attached to the text' : 'and a no-break space'}, in both registers`;
}

/**
 * The letters of a one-letter-word pattern, `([aAI])` → `a A I`; the pattern itself if it is not that shape.
 * `source` may hold a non-ASCII letter as `\uXXXX` (Bun escapes Cyrillic), so the escapes are read back first.
 */
function orphanLetters(pattern: RegExp): string {
  const match = /\(\[([^\]]+)\]\)/.exec(pattern.source);
  const letters = match?.[1]?.replace(/\\u([0-9a-fA-F]{4})/g, (_, hex: string) =>
    String.fromCharCode(Number.parseInt(hex, 16)),
  );
  return letters ? [...letters].join(' ') : `pattern ${code(pattern.source)}`;
}

/** A space character by name: the pack's highPunctuation holds the characters themselves. */
const SPACE_NAMES: Readonly<Record<string, string>> = {
  '\u00A0': 'no-break space (U+00A0)',
  '\u202F': 'narrow no-break space (U+202F)',
};
const spaceName = (space: string) =>
  SPACE_NAMES[space] ?? `U+${space.codePointAt(0)?.toString(16).toUpperCase().padStart(4, '0')}`;
/** What `space.high-punctuation` sets in the pack. */
const highSetting = (p: LangPack) =>
  p.highPunctuation
    ? `${p.highPunctuation.colon ? spaceName(p.highPunctuation.colon) : 'none'} before \`:\`, ${
        p.highPunctuation.others ? spaceName(p.highPunctuation.others) : 'none'
      } before \`; ! ?\`, after a letter or digit`
    : 'none';

export function renderPack(pack: LangPack): string {
  const out: string[] = [
    `# ${pack.name}`,
    '',
    `Code \`${pack.code}\`. ${pack.reviewed ? 'Read by a native speaker.' : '**Not reviewed by a native speaker.**'}`,
    '',
    'This page is generated by `bun run docs:languages` from the pack in `src/core/lang/' +
      `${fileOf(pack.code)}.ts` +
      '`. Do not edit it by hand: `src/lang-docs.test.ts` fails when it is out of date. A no-break space is shown as `~`.',
    '',
    '## Quotation',
    '',
    '| Register | Levels, outermost first |',
    '|---|---|',
    `| display | ${levels(pack.quotes)} |`,
    `| literary | ${pack.literary ? levels(pack.literary) : 'as display'} |`,
    '',
    'A quotation nested deeper than the levels listed starts over from the first.',
  ];
  if (pack.turnedPairs?.length) {
    out.push(
      '',
      `Read by where each mark stands, not only by shape: ${pack.turnedPairs.map(([o, c]) => code(`${o}…${c}`)).join(', ')} (turned the other way round from the usual guillemets).`,
    );
  }
  if (pack.sameMarkQuotes) {
    out.push('', 'The language opens and closes a quotation with the same mark.');
  }
  if (pack.openers) {
    out.push('', `An opening mark may also follow ${[...pack.openers].map(code).join(' ')}.`);
  }
  if (pack.elisions?.length) {
    out.push(
      '',
      `An apostrophe before a dropped-letter word is not a quotation mark: ${pack.elisions
        .map((w) => (w === 'n' ? "'n'" : `'${w}`))
        .map(code)
        .join(', ')}.`,
    );
  }
  out.push(
    '',
    `Words that end in an apostrophe, which stays an apostrophe and never closes a quotation: ${
      pack.truncations?.length ? pack.truncations.map((w) => code(`${w}'`)).join(', ') : 'none'
    }.`,
  );

  out.push(
    '',
    '## Dashes',
    '',
    '| What | Setting |',
    '|---|---|',
    `| break in the sentence | spaced ${pack.sentenceDash ? 'en dash' : 'em dash'} |`,
    `| break in the sentence, literary | spaced ${(pack.sentenceDashLiterary ?? pack.sentenceDash) ? 'en dash' : 'em dash'} |`,
    `| line of dialogue (a paragraph opening with a dash) | ${dialogueSetting(pack)} |`,
  );

  out.push('', '## Spaces', '');
  out.push(
    `- One-letter words kept with the next word: ${pack.orphans ? orphanLetters(pack.orphans) : 'none'}.`,
    `- Short words kept with the next word (\`space.short-word\`, on by default; the pack's own list): ${
      pack.shortWords?.length ? pack.shortWords.map(code).join(' ') : 'none'
    }.`,
    `- A no-break space between a number and %: ${pack.percentSpace ? 'yes' : 'no'}.`,
    `- A no-break space between a number and € after it: ${pack.currencySpace ? 'yes' : 'no'}.`,
    `- The space before \`:\` and before \`; ! ?\` (\`space.high-punctuation\`; the opt-in \`space.before-punctuation\` keeps it): ${highSetting(pack)}.`,
    `- A bare temperature without the degree sign (\`20 C\`) read as one (\`symbol.degree\`, opt-in): ${pack.bareTemperature ? 'yes' : 'no'}.`,
  );
  const lists = pack.abbreviations;
  if (lists && (lists.together || lists.bind || lists.page || lists.bare)) {
    out.push(
      '',
      '### Abbreviations',
      '',
      '| Kind | Entries |',
      '|---|---|',
      ...(lists.together
        ? [`| parts stay together | ${lists.together.map(code).join(' ')} |`]
        : []),
      ...(lists.bind ? [`| stay with what follows | ${lists.bind.map(code).join(' ')} |`] : []),
      ...(lists.page ? [`| stay with a number | ${lists.page.map(code).join(' ')} |`] : []),
      ...(lists.bare
        ? [`| no full stop, stay with a number | ${lists.bare.map(code).join(' ')} |`]
        : []),
    );
  } else {
    out.push('- Abbreviations: no list.');
  }

  out.push('', '## Numbers', '');
  out.push(
    pack.numbers
      ? `Groups of three are separated by ${code(pack.numbers.group)}, the decimal mark is ${code(pack.numbers.decimal.charAt(0))}${
          pack.numbers.decimal.length > 1
            ? ` (also ${[...pack.numbers.decimal.slice(1)].map(code).join(', ')} in amounts)`
            : ''
        }.`
      : 'No number format yet.',
  );

  out.push('', '## Sources', '');
  out.push(
    ...(pack.sources.length ? pack.sources.map((s) => `- ${marks(s)}`) : ['None cited yet.']),
  );

  out.push('', '## Notes', '', marks(pack.notes));
  return `${out.join('\n')}\n`;
}

export function renderIndex(): string {
  const out = [
    '# Languages',
    '',
    `The package has ${PACKS.length} language packs. Each has a page here, generated from the pack in \`src/core/lang/\`. The hand-written overview is [../languages.md](../languages.md).`,
    '',
    'This file is generated by `bun run docs:languages`. Do not edit it by hand: `src/lang-docs.test.ts` fails when it is out of date.',
    '',
    '| Code | Language | Display quotes | Reviewed | Sources |',
    '|---|---|---|---|---|',
    ...PACKS.map(
      (pack: LangPack) =>
        `| [\`${pack.code}\`](${fileOf(pack.code)}.md) | ${pack.name} | ${levelOf(pack.quotes[0] as Level)} | ${pack.reviewed ? 'yes' : 'no'} | ${pack.sources.length || 'none'} |`,
    ),
  ];
  return `${out.join('\n')}\n`;
}

/** Every generated page: file name to content. */
export function renderAll(): Record<string, string> {
  return {
    'index.md': renderIndex(),
    ...Object.fromEntries(
      PACKS.map((pack: LangPack) => [`${fileOf(pack.code)}.md`, renderPack(pack)]),
    ),
  };
}

if (import.meta.main) {
  mkdirSync(DIR, { recursive: true });
  for (const [name, content] of Object.entries(renderAll())) {
    writeFileSync(join(DIR, name), content);
  }
}
